package speclok;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayDeque;
import java.util.Arrays;
import java.util.Deque;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;


/**
 * Generates the <em>agent briefing</em> for one task - everything the implementer needs to
 * work on it - straight from the {@code @Spec}/{@code @AC} annotations. The help the AI reads
 * stops living in scattered files ({@code AGENTS.md}, {@code .claude/agents/*.md}, a {@code .yaml}
 * manifest, a separate context-pack) and becomes <b>derived</b> from the one source of truth, exactly
 * like the spec, the docs and the verification.
 * <p>
 * Runs as a speclok app: {@code java -jar speclok.jar specctx <TASK_ID> [src-root...] [-o out.md]}.
 * Includes the context-pack: each {@code simbolo} resolved to {@code file:line} by a self-contained
 * Java indexer (port of {@code .sdd/routing/symbol_locate.py}), so the agent opens the exact spot
 * without searching. Deterministic, no LLM.
 */
public class SpecContextApp {
	public String getAppName() {
		return "specctx";
	}

	public String getAppDescription() {
		return "Prints the agent briefing (constitution + task + context-pack + criteria) for a task id, from @Spec/@AC.";
	}

	public int runApp(List<String> args) throws Exception {
		String taskId = null;
		Path out = null;
		java.util.List<Path> roots = new java.util.ArrayList<Path>();
		for (int i = 0; i < args.size(); i++) {
			String a = args.get(i);
			if ("-o".equals(a) && i + 1 < args.size()) out = Paths.get(args.get(++i));
			else if (taskId == null) taskId = a;
			else roots.add(Paths.get(a));
		}
		if (taskId == null) {
			System.err.println("usage: specctx <TASK_ID> [src-root...] [-o out.md]");
			return 2;
		}
		if (roots.isEmpty()) roots.add(Paths.get("."));

		SpecBookApp.Spec target = null;
		Map<String, String> symIndex = new LinkedHashMap<String, String>(); // name -> "rel:line"
		for (Path root : roots) {
			if (!Files.exists(root)) continue;
			try (Stream<Path> walk = Files.walk(root)) {
				for (Path p : (Iterable<Path>) walk::iterator) {
					if (!p.toString().endsWith(".java")) continue;
					String text = new String(Files.readAllBytes(p), StandardCharsets.UTF_8);
					String rel = root.relativize(p).toString().replace('\\', '/');
					indexJava(text, rel, symIndex);                      // index EVERY file for the context-pack
					if (target == null && text.contains("@Spec")) {
						SpecBookApp.Spec s = SpecBookApp.manifestFromText(text, rel);
						if (s != null && taskId.equals(s.id)) target = s;
					}
				}
			}
		}

		if (target == null) {
			System.err.println("specctx: no @Spec with id=" + taskId + " in roots " + roots);
			return 1;
		}

		String md = render(target, symIndex);
		if (out != null) {
			Files.write(out, md.getBytes(StandardCharsets.UTF_8));
			System.out.println("written: " + out + "  (briefing for " + taskId + ", derived from @Spec)");
		} else {
			System.out.print(md);
		}
		return 0;
	}

	// ---- render the briefing -------------------------------------------------

	private static String render(SpecBookApp.Spec s, Map<String, String> symIndex) {
		StringBuilder b = new StringBuilder();
		b.append("# Agent briefing · ").append(s.id).append("\n\n");
		b.append("> **Generated by speclok from `@Spec`** - not a hand-maintained file. ")
		 .append("Everything you need to implement this task is here.\n\n");

		b.append("## Constitution (governing rules - always apply)\n\n");
		for (int i = 0; i < SpecBookApp.CONSTITUTION.length; i++)
			b.append(i + 1).append(". **").append(SpecBookApp.CONSTITUTION[i][0]).append(".** ")
			 .append(SpecBookApp.CONSTITUTION[i][1]).append("\n");

		b.append("\n## The task\n\n");
		b.append("- **Objective**: ").append(s.objective).append("\n");
		if (!s.allowedFiles.isEmpty()) b.append("- **May only edit** (allowedFiles): ").append(joinCode(s.allowedFiles)).append("\n");
		if (!s.outOfScope.isEmpty()) b.append("- **Do NOT** (out of scope): ").append(String.join(", ", s.outOfScope)).append("\n");

		b.append("\n## Context pack - open directly, no searching\n\n");
		if (s.symbols.isEmpty()) {
			b.append("_(the spec listed no symbols)_\n");
		} else {
			for (String sym : s.symbols) {
				String loc = symIndex.get(sym);
				b.append("- `").append(sym).append("` → ").append(loc == null ? "_(unresolved)_" : "`" + loc + "`").append("\n");
			}
		}

		b.append("\n## Acceptance criteria - only done when ALL pass\n\n");
		if (s.acs.isEmpty()) {
			b.append("_(the spec has no @AC)_\n");
		} else {
			b.append("| AC | Given | When | Then |\n|----|-------|------|------|\n");
			for (String[] ac : s.acs)
				b.append("| **").append(ac[0]).append("** | ").append(cell(ac[1])).append(" | ")
				 .append(cell(ac[2])).append(" | ").append(cell(ac[3])).append(" |\n");
			b.append("\n> Convention: each @AC has a test whose name starts with `").append(s.acs.get(0)[0]).append("_`.\n");
		}
		return b.toString();
	}

	private static String cell(String s) { return s.replace("|", "\\|"); }

	private static String joinCode(List<String> xs) {
		StringBuilder b = new StringBuilder();
		for (String x : xs) { if (b.length() > 0) b.append(", "); b.append('`').append(x).append('`'); }
		return b.toString();
	}

	// ---- Java symbol indexer (port of symbol_locate.py) ----------------------

	private static final Pattern TYPE = Pattern.compile("\\b(?:class|enum|interface)\\s+(\\w+)");
	private static final Pattern METHOD = Pattern.compile(
		"\\s*(?:@\\w+\\s*(?:\\([^)]*\\))?\\s*)*"
		+ "(?:(?:public|private|protected|static|final|abstract|default|synchronized|native|strictfp)\\s+)*"
		+ "(?:<[^>]+>\\s+)?[\\w\\[\\]<>,.?\\s]+?\\s+(\\w+)\\s*\\(");
	private static final Set<String> NOT_METHOD = new HashSet<String>(Arrays.asList(
		"if", "for", "while", "switch", "catch", "return", "new", "synchronized"));

	/** Indexes {Type: rel:line, Type.method: rel:line} by brace counting (comments/strings
	 * neutralized). putIfAbsent: the first occurrence wins. */
	static void indexJava(String raw, String rel, Map<String, String> out) {
		String[] lines = blankJava(raw).split("\n", -1);
		int depth = 0;
		Deque<Object[]> stack = new ArrayDeque<Object[]>();  // [name, startLine, openDepth]
		for (int i = 0; i < lines.length; i++) {
			String line = lines[i];
			int before = depth;
			Matcher tm = TYPE.matcher(line);
			if (tm.find() && before <= 1) {
				String name = tm.group(1);
				out.putIfAbsent(name, rel + ":" + (i + 1));
				stack.push(new Object[] {name, i + 1, Integer.valueOf(before)});
			}
			if (!stack.isEmpty()) {
				Object[] top = stack.peek();
				String tname = (String) top[0];
				int tdepth = ((Integer) top[2]).intValue();
				if (before == tdepth + 1) {
					Matcher mm = METHOD.matcher(line);
					if (mm.lookingAt() && (line.indexOf('{') >= 0 || line.indexOf(';') >= 0 || line.contains("throws"))) {
						String mname = mm.group(1);
						if (!NOT_METHOD.contains(mname) && !mname.equals(tname))
							out.putIfAbsent(tname + "." + mname, rel + ":" + (i + 1));
					}
				}
			}
			for (int k = 0; k < line.length(); k++) {
				char c = line.charAt(k);
				if (c == '{') depth++;
				else if (c == '}') depth--;
			}
			while (!stack.isEmpty() && depth <= ((Integer) stack.peek()[2]).intValue()) stack.pop();
		}
	}

	/** Replaces the content of comments and literals with spaces, preserving line breaks and the `{}`. */
	static String blankJava(String t) {
		StringBuilder out = new StringBuilder(t.length());
		int i = 0, n = t.length(), mode = 0; // 0 none, 1 line, 2 block, 3 str, 4 char
		while (i < n) {
			char c = t.charAt(i);
			char nx = i + 1 < n ? t.charAt(i + 1) : '\0';
			if (mode == 0) {
				if (c == '/' && nx == '/') { mode = 1; out.append("  "); i += 2; continue; }
				if (c == '/' && nx == '*') { mode = 2; out.append("  "); i += 2; continue; }
				if (c == '"') { mode = 3; out.append('"'); i++; continue; }
				if (c == '\'') { mode = 4; out.append('\''); i++; continue; }
				out.append(c); i++;
			} else if (mode == 1) {
				if (c == '\n') { mode = 0; out.append('\n'); } else out.append(' ');
				i++;
			} else if (mode == 2) {
				if (c == '*' && nx == '/') { mode = 0; out.append("  "); i += 2; continue; }
				out.append(c == '\n' ? '\n' : ' '); i++;
			} else {
				char q = mode == 3 ? '"' : '\'';
				if (c == '\\') { out.append("  "); i += 2; continue; }
				if (c == q) { mode = 0; out.append(q); i++; continue; }
				out.append(c == '\n' ? '\n' : ' '); i++;
			}
		}
		return out.toString();
	}

	/** Standalone for testing: {@code java speclok.SpecContextApp <TASK_ID> <root> [-o out.md]}. */
	public static void main(String[] args) throws Exception {
		System.exit(new SpecContextApp().runApp(Arrays.asList(args)));
	}
}
